"""Carry the caller's session id to Portkey as the trace id, per request.

Every deployment's litellm_params.extra_headers holds its x-portkey-config name
(generated by build.py). A request-level extra_headers would replace that dict,
so instead this filter hook hands LiteLLM per-request copies of the candidate
deployments with the trace headers merged in. Portkey's request log then names
the same id as usage.db and Team's ledger.

  x-portkey-trace-id   = x-litellm-session-id (the Team job, or a smoke id)
  x-portkey-metadata   = {"session": <id>, "caller": "litellm", "group": <model_name asked for>}
"""

from __future__ import annotations

import copy
import json

from litellm.integrations.custom_logger import CustomLogger
from litellm.router_utils.pre_call_checks.deployment_affinity_check import DeploymentAffinityCheck


class ForwardHeaders(CustomLogger):
    async def async_filter_deployments(self, model, healthy_deployments, messages,
                                       request_kwargs=None, parent_otel_span=None):
        kwargs = request_kwargs or {}
        session = DeploymentAffinityCheck._get_session_id_from_request_kwargs(kwargs)
        if not session:
            return healthy_deployments
        extra = {
            "x-portkey-trace-id": str(session),
            "x-portkey-metadata": json.dumps({"session": str(session), "caller": "litellm", "group": model},
                                             separators=(",", ":")),
        }
        out = []
        for d in healthy_deployments:
            d = copy.copy(d)
            params = dict(d.get("litellm_params") or {})
            params["extra_headers"] = {**(params.get("extra_headers") or {}), **extra}
            d["litellm_params"] = params
            out.append(d)
        return out


forward = ForwardHeaders()
