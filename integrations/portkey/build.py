#!/usr/bin/env python3
"""One catalog in, four outputs out; refuse anything that is not free.

    build.py            write every output under $HOME/state/team (mode 600)
    build.py --check    exit 1 unless every output on disk is exactly what catalog.json generates

Outputs (all derived from catalog.json beside this file and the keys in
$HOME/state/team/portkey/.env):
  portkey/configs/team-model-<slug>.json   one per routed model: Portkey fallback over its providers
  portkey/configs/team-tier-<tier>.json    one per tier: fallback over every model of the tier, in order
  portkey/conf.json                        the console admin token
  litellm/config.yaml                      every deployment points at Portkey by config name

Stale team-*.json files in configs/ are removed on build and count as drift on --check.
No PyYAML: the YAML is written by the small emitter below so a port (the Rust one) can
match it byte for byte. Standard library only.

TEAM_STATE_DIR overrides $HOME/state/team (used by the tests).
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CATALOG = HERE / "catalog.json"
FREE = {"yes", "allowance"}
NAME = re.compile(r"^[a-z0-9-]+$")
MAX_CONFIG_BYTES = 12 * 1024
ON_STATUS = [429, 500, 502, 503, 529]
DEFAULT_TIMEOUT_MS = 60000
GEN_JSON = "generated by integrations/portkey/build.py from catalog.json; edit the catalog, then rebuild"


class Refusal(SystemExit):
    def __init__(self, msg: str) -> None:
        super().__init__(f"build.py: refusing: {msg}")
        self.msg = msg


def refuse(msg: str) -> None:
    raise Refusal(msg)


def state_dir() -> Path:
    return Path(os.environ.get("TEAM_STATE_DIR") or Path.home() / "state" / "team")


def read_env(path: Path) -> dict[str, str]:
    """KEY=value lines; no quoting, no expansion, # comments."""
    if not path.exists():
        refuse(f"{path} is missing; it must hold every provider key named in the catalog")
    out = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        out[k.strip()] = v.strip()
    return out


def slug(model_id: str) -> str:
    return re.sub(r"[^a-z0-9-]", "-", model_id)


# ---------- YAML emitter (deterministic, subset) ----------

PLAIN = re.compile(r"^[A-Za-z_][A-Za-z0-9_./-]*$")
RESERVED = {"true", "false", "null", "yes", "no", "on", "off", "y", "n", "~"}


def yscalar(v) -> str:
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, (int, float)):
        return repr(v)
    s = str(v)
    if PLAIN.match(s) and s.lower() not in RESERVED:
        return s
    return json.dumps(s, ensure_ascii=False)


def yaml_lines(v, indent: int = 0) -> list[str]:
    pad = " " * indent
    if isinstance(v, dict):
        if not v:
            return [pad + "{}"]
        out = []
        for k, val in v.items():
            key = yscalar(k)
            if isinstance(val, dict) and val:
                out.append(f"{pad}{key}:")
                out.extend(yaml_lines(val, indent + 2))
            elif isinstance(val, list) and val:
                out.append(f"{pad}{key}:")
                out.extend(yaml_lines(val, indent))
            else:
                out.append(f"{pad}{key}: {yaml_lines(val, 0)[0]}")
        return out
    if isinstance(v, list):
        if not v:
            return [pad + "[]"]
        out = []
        for item in v:
            if isinstance(item, (dict, list)) and item:
                sub = yaml_lines(item, indent + 2)
                out.append(f"{pad}- {sub[0][indent + 2:]}")
                out.extend(sub[1:])
            else:
                out.append(f"{pad}- {yaml_lines(item, 0)[0]}")
        return out
    return [pad + yscalar(v)]


def yaml_dump(v) -> str:
    return "\n".join(yaml_lines(v)) + "\n"


def json_dump(v) -> str:
    return json.dumps(v, indent=2, ensure_ascii=False) + "\n"


# ---------- the catalog, checked ----------

def routed(catalog: dict) -> list[dict]:
    """Routed models in tier order, each with its available served_by rows; refuse what is not free."""
    blocked = catalog["blocked_providers"]
    providers = catalog["providers"]
    tiers = catalog["tiers"]
    seen_ids, seen_slugs = set(), set()
    out = []
    for m in catalog["models"]:
        mid = m["id"]
        if mid in seen_ids:
            refuse(f"{mid}: duplicate model id")
        seen_ids.add(mid)
        if not m.get("served_by"):
            refuse(f"{mid}: no served_by")
        for s in m["served_by"]:
            p = s["provider"]
            if p in blocked:
                refuse(f"{mid}: provider {p} is blocked ({blocked[p]})")
            if p not in providers:
                refuse(f"{mid}: unknown provider {p}")
            if s.get("free") not in FREE:
                refuse(f"{mid} via {p}: free is {s.get('free')!r}")
            if p == "openrouter" and not s["provider_model_id"].endswith(":free"):
                refuse(f"{mid} via openrouter: {s['provider_model_id']} is not a ':free' variant")
        if m.get("tier") is None:
            continue
        if m["tier"] not in tiers:
            refuse(f"{mid}: unknown tier {m['tier']!r}")
        if not isinstance(m.get("order"), int) or m["order"] < 1:
            refuse(f"{mid}: order must be an integer >= 1")
        sl = slug(mid)
        if not NAME.match(sl):
            refuse(f"{mid}: slug {sl!r} is not a config name")
        if sl in seen_slugs:
            refuse(f"{mid}: slug {sl} collides with another model")
        seen_slugs.add(sl)
        live = [s for s in m["served_by"] if not s.get("unavailable")]
        if not live:
            refuse(f"{mid}: routed in tier {m['tier']} but every provider is marked unavailable")
        out.append({**m, "slug": sl, "live": live})
    for t in tiers:
        if not any(m["tier"] == t for m in out):
            refuse(f"tier {t} has no models")
    for p, spec in providers.items():
        if p in blocked:
            refuse(f"provider {p} is both configured and blocked")
        if not spec.get("portkey") or not spec.get("key_env"):
            refuse(f"provider {p}: needs 'portkey' slug and 'key_env'")
    return out


def tier_models(models: list[dict], tier: str) -> list[dict]:
    return sorted((m for m in models if m["tier"] == tier), key=lambda m: m["order"])


# ---------- Portkey ----------

def target(catalog: dict, m: dict, s: dict, keys: dict[str, str]) -> dict:
    p = catalog["providers"][s["provider"]]
    key = keys.get(p["key_env"])
    if not key:
        refuse(f"{m['id']} via {s['provider']}: {p['key_env']} is not set in Portkey's .env")
    t = {"provider": p["portkey"], "api_key": key}
    if p.get("custom_host"):
        t["custom_host"] = p["custom_host"]
    t["override_params"] = {"model": s["provider_model_id"]}
    t["retry"] = {"attempts": 1, "on_status_codes": ON_STATUS}
    t["request_timeout"] = int(p.get("request_timeout_ms") or DEFAULT_TIMEOUT_MS)
    return t


def model_config(catalog: dict, m: dict, keys: dict[str, str]) -> dict:
    return {
        "_": f"{GEN_JSON}; model {m['id']} in tier {m['tier']}",
        "strategy": {"mode": "fallback", "on_status_codes": ON_STATUS},
        "targets": [target(catalog, m, s, keys) for s in m["live"]],
    }


def tier_config(catalog: dict, models: list[dict], tier: str, keys: dict[str, str]) -> dict:
    return {
        "_": f"{GEN_JSON}; tier {tier}, models in order; LiteLLM is the normal path, this is for status checks",
        "strategy": {"mode": "fallback", "on_status_codes": ON_STATUS},
        "targets": [
            {
                "strategy": {"mode": "fallback", "on_status_codes": ON_STATUS},
                "targets": [target(catalog, m, s, keys) for s in m["live"]],
            }
            for m in tier_models(models, tier)
        ],
    }


def timeout_s(catalog: dict, m: dict) -> int:
    ms = sum(int(catalog["providers"][s["provider"]].get("request_timeout_ms") or DEFAULT_TIMEOUT_MS) for s in m["live"])
    return ms // 1000 + 10


# ---------- LiteLLM ----------

def deployment(catalog: dict, m: dict, group: str, dep_id: str) -> dict:
    g = catalog["gateway"]
    params = {
        "model": f"openai/{m['id']}",
        "api_base": f"http://{g['host']}:{g['port']}/v1",
        "api_key": "team",
        "extra_headers": {"x-portkey-config": f"team-model-{m['slug']}"},
        "order": m["order"],
        "timeout": timeout_s(catalog, m),
    }
    info = {"id": dep_id, "input_cost_per_token": 0, "output_cost_per_token": 0}
    cap = m.get("max_input") or m["live"][0].get("max_input") or m.get("context")
    if cap:
        info["max_input_tokens"] = cap
    if m.get("max_output"):
        info["max_output_tokens"] = m["max_output"]
    if m.get("tools") is not None:
        info["supports_function_calling"] = bool(m["tools"])
        info["supports_tool_choice"] = bool(m["tools"])
    if m.get("vision") is not None:
        info["supports_vision"] = bool(m["vision"])
    if m.get("reasoning") is not None:
        info["supports_reasoning"] = bool(m["reasoning"])
    return {"model_name": group, "litellm_params": params, "model_info": info}


def litellm_config(catalog: dict, models: list[dict]) -> dict:
    tiers = catalog["tiers"]
    model_list = []
    for t in tiers:
        for m in tier_models(models, t):
            model_list.append(deployment(catalog, m, m["id"], m["slug"]))
            model_list.append(deployment(catalog, m, f"tier-{t}", f"tier-{t}/{m['slug']}"))
    fb = catalog["tier_fallbacks"]
    return {
        "model_list": model_list,
        "router_settings": {
            "enable_pre_call_checks": True,
            "num_retries": 1,
            "max_fallbacks": 2,
            "allowed_fails": 1,
            "cooldown_time": 300,
            "fallbacks": [{f"tier-{t}": [f"tier-{f}" for f in fb[t]]} for t in tiers],
            "context_window_fallbacks": [],
        },
        "litellm_settings": {
            "drop_params": True,
            "telemetry": False,
            "callbacks": ["forward_headers.forward", "session_pin.pin", "usage_log.logger"],
        },
        "general_settings": {"master_key": "os.environ/LITELLM_MASTER_KEY"},
    }


# ---------- all four ----------

def render(catalog: dict, keys: dict[str, str]) -> dict[str, str]:
    """Relative path under the state dir -> exact file text."""
    models = routed(catalog)
    out: dict[str, str] = {}
    for m in models:
        out[f"portkey/configs/team-model-{m['slug']}.json"] = json_dump(model_config(catalog, m, keys))
    for t in catalog["tiers"]:
        out[f"portkey/configs/team-tier-{t}.json"] = json_dump(tier_config(catalog, models, t, keys))
    for path, text in out.items():
        if len(text.encode()) > MAX_CONFIG_BYTES:
            refuse(f"{path} is {len(text.encode())} bytes, over {MAX_CONFIG_BYTES}")
    token = keys.get("PORTKEY_ADMIN_TOKEN")
    if not token:
        refuse("PORTKEY_ADMIN_TOKEN is not set in Portkey's .env")
    out["portkey/conf.json"] = json_dump({"admin_token": token})
    head = "# GENERATED by integrations/portkey/build.py from catalog.json. Edit the catalog, then rebuild.\n"
    out["litellm/config.yaml"] = head + yaml_dump(litellm_config(catalog, models))
    return out


def generated_on_disk(state: Path) -> set[str]:
    cfg = state / "portkey" / "configs"
    return {f"portkey/configs/{p.name}" for p in cfg.glob("team-*.json")} if cfg.exists() else set()


def drift(state: Path, files: dict[str, str]) -> list[str]:
    problems = []
    for rel, text in files.items():
        p = state / rel
        if not p.exists():
            problems.append(f"missing {rel}")
        elif p.read_text() != text:
            problems.append(f"differs {rel}")
    for rel in sorted(generated_on_disk(state) - set(files)):
        problems.append(f"stale {rel}")
    return problems


def write(state: Path, files: dict[str, str]) -> None:
    for rel in generated_on_disk(state) - set(files):
        (state / rel).unlink()
    for rel, text in files.items():
        p = state / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        tmp = p.with_name(p.name + ".tmp")
        with open(os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600), "w") as f:
            f.write(text)
        os.chmod(tmp, 0o600)
        os.replace(tmp, p)


def main(argv: list[str]) -> int:
    state = state_dir()
    catalog = json.loads(CATALOG.read_text())
    keys = read_env(state / "portkey" / ".env")
    files = render(catalog, keys)
    if "--check" in argv:
        problems = drift(state, files)
        if problems:
            refuse("outputs are not what catalog.json generates: " + "; ".join(problems) + "; run build.py")
        print(f"build.py --check: {len(files)} files match catalog.json")
        return 0
    write(state, files)
    print(f"build.py: wrote {len(files)} files under {state}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
