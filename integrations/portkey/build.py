#!/usr/bin/env python3
"""One catalog in, three kinds of output; refuse anything that is not free.

    build.py            write every output under $HOME/state/team (mode 600)
    build.py --check    exit 1 unless every output on disk is exactly what catalog.json generates

Outputs (all derived from catalog.json beside this file and the keys in
$HOME/state/team/portkey/.env):
  portkey/configs/team-model-<slug>.json   one per routed model: Portkey fallback over its providers
  portkey/configs/team-tier-<tier>.json    one per tier: fallback over every model of the tier, in order
  portkey/configs/team-probe-<provider>.json  one per provider: only that provider, on its first routed
                                           model, so a key can be tested on its own (the dashboard's probe)
  portkey/configs/team-pair-<slug>--<provider>.json  one per served_by row of every model, routed or not,
                                           unavailable or not, whose key is set: that model on that
                                           provider alone, so the dashboard can verify each one
  litellm/config.yaml                      every deployment points at Portkey by config name
  litellm/allowances.json                  per provider with a monthly allowance (paid per token out of an
                                           included credit): budget, stop, cycle day, per-model prices and
                                           every config name that reaches it; read by spend.py

(PLAN.md also lists portkey/conf.json with an admin token for the console; Portkey v1.15.2 has no
admin token and reads ./conf.json only for settings behind FETCH_SETTINGS_FROM_FILE, so nothing
is generated for it. cb_config is likewise not emitted: the open-source gateway never reads it.)

Stale team-*.json files in configs/ are removed on build and count as drift on --check.
No PyYAML: the YAML is written by the small emitter below so a port (the Rust one) can
match it byte for byte. Standard library only.

TEAM_STATE overrides $HOME/state/team (used by the tests).
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CATALOG = HERE / "catalog.json"
FREE = {"yes", "allowance"}
NAME = re.compile(r"^[a-z0-9-]+$")
MAX_CONFIG_BYTES = 12 * 1024
# Retry, failover, timeout and router values live in catalog.json's policy section; policy() checks them.
MODES = {"fallback", "loadbalance"}
ROUTING = {"simple-shuffle", "least-busy", "latency-based-routing", "usage-based-routing", "usage-based-routing-v2"}
GEN_JSON = "generated by integrations/portkey/build.py from catalog.json; edit the catalog, then rebuild"


class Refusal(SystemExit):
    def __init__(self, msg: str) -> None:
        super().__init__(f"build.py: refusing: {msg}")
        self.msg = msg


def refuse(msg: str) -> None:
    raise Refusal(msg)


def state_dir() -> Path:
    return Path(os.environ.get("TEAM_STATE") or Path.home() / "state" / "team")


def read_env(path: Path) -> dict[str, str]:
    """KEY=value lines; no quoting, no expansion, # comments."""
    if not path.exists():
        refuse(f"{path} is missing; it must hold every provider key named in the catalog")
    out = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        out[k.strip()] = v.strip()
    return out


def slug(model_id: str) -> str:
    return re.sub(r"[^a-z0-9-]", "-", model_id)


# ---------- YAML emitter (deterministic, subset) ----------

PLAIN = re.compile(r"^[A-Za-z_][A-Za-z0-9_./-]*$")
RESERVED = {"true", "false", "null", "yes", "no", "on", "off", "y", "n", "~"}


def yscalar(v) -> str:
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, (int, float)):
        return repr(v)
    s = str(v)
    if PLAIN.match(s) and s.lower() not in RESERVED:
        return s
    return json.dumps(s, ensure_ascii=False)


def yaml_lines(v, indent: int = 0) -> list[str]:
    pad = " " * indent
    if isinstance(v, dict):
        if not v:
            return [pad + "{}"]
        out = []
        for k, val in v.items():
            key = yscalar(k)
            if isinstance(val, dict) and val:
                out.append(f"{pad}{key}:")
                out.extend(yaml_lines(val, indent + 2))
            elif isinstance(val, list) and val:
                out.append(f"{pad}{key}:")
                out.extend(yaml_lines(val, indent))
            else:
                out.append(f"{pad}{key}: {yaml_lines(val, 0)[0]}")
        return out
    if isinstance(v, list):
        if not v:
            return [pad + "[]"]
        out = []
        for item in v:
            if isinstance(item, (dict, list)) and item:
                sub = yaml_lines(item, indent + 2)
                out.append(f"{pad}- {sub[0][indent + 2:]}")
                out.extend(sub[1:])
            else:
                out.append(f"{pad}- {yaml_lines(item, 0)[0]}")
        return out
    return [pad + yscalar(v)]


def yaml_dump(v) -> str:
    return "\n".join(yaml_lines(v)) + "\n"


def json_dump(v) -> str:
    return json.dumps(v, indent=2, ensure_ascii=False) + "\n"


# ---------- the catalog, checked ----------

def routed(catalog: dict) -> list[dict]:
    """Routed models in tier order, each with its available served_by rows; refuse what is not free."""
    blocked = catalog["blocked_providers"]
    providers = catalog["providers"]
    tiers = catalog["tiers"]
    seen_ids, seen_slugs = set(), set()
    out = []
    for m in catalog["models"]:
        mid = m["id"]
        if mid in seen_ids:
            refuse(f"{mid}: duplicate model id")
        seen_ids.add(mid)
        if not m.get("served_by"):
            refuse(f"{mid}: no served_by")
        for s in m["served_by"]:
            p = s["provider"]
            if p in blocked:
                refuse(f"{mid}: provider {p} is blocked ({blocked[p]})")
            if p not in providers:
                refuse(f"{mid}: unknown provider {p}")
            if s.get("free") not in FREE:
                refuse(f"{mid} via {p}: free is {s.get('free')!r}")
            if p == "openrouter" and not s["provider_model_id"].endswith(":free"):
                refuse(f"{mid} via openrouter: {s['provider_model_id']} is not a ':free' variant")
            w = s.get("weight")
            if w is not None and (isinstance(w, bool) or not isinstance(w, (int, float)) or w <= 0):
                refuse(f"{mid} via {p}: weight must be a number > 0, not {w!r}")
        if m.get("tier") is None:
            continue
        if m["tier"] not in tiers:
            refuse(f"{mid}: unknown tier {m['tier']!r}")
        if not isinstance(m.get("order"), int) or m["order"] < 1:
            refuse(f"{mid}: order must be an integer >= 1")
        sl = slug(mid)
        if not NAME.match(sl):
            refuse(f"{mid}: slug {sl!r} is not a config name")
        if sl in seen_slugs:
            refuse(f"{mid}: slug {sl} collides with another model")
        seen_slugs.add(sl)
        live = [s for s in m["served_by"] if not s.get("unavailable")]
        if not live:
            refuse(f"{mid}: routed in tier {m['tier']} but every provider is marked unavailable")
        out.append({**m, "slug": sl, "live": live})
    for t in tiers:
        if not any(m["tier"] == t for m in out):
            refuse(f"tier {t} has no models")
    for p, spec in providers.items():
        if p in blocked:
            refuse(f"provider {p} is both configured and blocked")
        if not spec.get("portkey") or not spec.get("key_env"):
            refuse(f"provider {p}: needs 'portkey' slug and 'key_env'")
        if "allowance" in spec:
            check_allowance(p, spec["allowance"])
    for m in catalog["models"]:
        metered = [s["provider"] for s in m["served_by"] if "allowance" in providers[s["provider"]]]
        if not metered:
            continue
        if len(m["served_by"]) != len(metered) or len(set(metered)) != 1:
            refuse(f"{m['id']}: a model on an allowance provider must be served by that provider alone, "
                   f"so the spend guard can stop it")
        if any(s.get("free") != "allowance" for s in m["served_by"]):
            refuse(f"{m['id']}: rows on an allowance provider must say free: allowance")
        check_price(m["id"], m.get("price"))
    return out


def number(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def check_allowance(p: str, a) -> None:
    if not isinstance(a, dict):
        refuse(f"provider {p}: allowance must be an object")
    if not number(a.get("monthly_usd")) or a["monthly_usd"] <= 0:
        refuse(f"provider {p}: allowance.monthly_usd must be a number > 0")
    if not number(a.get("stop_at_usd")) or not 0 < a["stop_at_usd"] <= a["monthly_usd"]:
        refuse(f"provider {p}: allowance.stop_at_usd must be > 0 and at most monthly_usd")
    d = a.get("cycle_day")
    if isinstance(d, bool) or not isinstance(d, int) or not 1 <= d <= 28:
        refuse(f"provider {p}: allowance.cycle_day must be an integer 1-28")


def check_price(mid: str, price) -> None:
    if not isinstance(price, dict):
        refuse(f"{mid}: a model on an allowance provider needs a price (input_per_mtok, output_per_mtok)")
    for k in ("input_per_mtok", "output_per_mtok"):
        if not number(price.get(k)) or price[k] < 0:
            refuse(f"{mid}: price.{k} must be a number >= 0")
    long_keys = ("long_prompt_over", "long_input_per_mtok", "long_output_per_mtok")
    present = [k for k in long_keys if k in price]
    if present and (len(present) != 3 or any(not number(price[k]) or price[k] < 0 for k in long_keys)):
        refuse(f"{mid}: price needs all of {', '.join(long_keys)} or none")


def tier_models(models: list[dict], tier: str) -> list[dict]:
    return sorted((m for m in models if m["tier"] == tier), key=lambda m: m["order"])


def policy(catalog: dict) -> dict:
    """The catalog's policy section, checked; '*_why' and 'about' keys are notes and are ignored."""
    pol = catalog.get("policy")
    if not isinstance(pol, dict) or not isinstance(pol.get("portkey"), dict) or not isinstance(pol.get("litellm"), dict):
        refuse("policy: needs 'portkey' and 'litellm' sections")
    pk, ll = pol["portkey"], pol["litellm"]

    def count(sec: dict, name: str, key: str, lo: int = 0) -> int:
        v = sec.get(key)
        if isinstance(v, bool) or not isinstance(v, int) or v < lo:
            refuse(f"policy.{name}.{key} must be an integer >= {lo}, not {v!r}")
        return v

    def flag(sec: dict, name: str, key: str) -> bool:
        v = sec.get(key)
        if not isinstance(v, bool):
            refuse(f"policy.{name}.{key} must be true or false, not {v!r}")
        return v

    def statuses(key: str) -> list[int]:
        v = pk.get(key)
        if (not isinstance(v, list) or not v
                or any(isinstance(c, bool) or not isinstance(c, int) or not 400 <= c <= 599 for c in v)):
            refuse(f"policy.portkey.{key} must be a non-empty list of HTTP error statuses (400-599), not {v!r}")
        return v

    if pk.get("mode") not in MODES:
        refuse(f"policy.portkey.mode must be one of {sorted(MODES)}, not {pk.get('mode')!r}")
    strategy = ll.get("routing_strategy")
    if strategy is not None and strategy not in ROUTING:
        refuse(f"policy.litellm.routing_strategy must be null or one of {sorted(ROUTING)}, not {strategy!r}")
    tiers = catalog["tiers"]
    cwf = ll.get("context_window_fallbacks")
    if not isinstance(cwf, dict):
        refuse("policy.litellm.context_window_fallbacks must be an object of tier -> [tiers]")
    for t, to in cwf.items():
        if t not in tiers or not isinstance(to, list) or not to or any(x not in tiers or x == t for x in to):
            refuse(f"policy.litellm.context_window_fallbacks.{t}: must be a known tier -> other known tiers, not {to!r}")
    return {
        "portkey": {
            "mode": pk["mode"],
            "on_status_codes": statuses("on_status_codes"),
            "retry_attempts": count(pk, "portkey", "retry_attempts"),
            "retry_on_status_codes": statuses("retry_on_status_codes"),
            "default_timeout_ms": count(pk, "portkey", "default_timeout_ms", 1000),
        },
        "litellm": {
            "routing_strategy": strategy,
            "enable_pre_call_checks": flag(ll, "litellm", "enable_pre_call_checks"),
            "num_retries": count(ll, "litellm", "num_retries"),
            "max_fallbacks": count(ll, "litellm", "max_fallbacks"),
            "allowed_fails": count(ll, "litellm", "allowed_fails"),
            "cooldown_time": count(ll, "litellm", "cooldown_time"),
            "context_window_fallbacks": cwf,
            "drop_params": flag(ll, "litellm", "drop_params"),
            "session_pin_ttl_s": count(ll, "litellm", "session_pin_ttl_s", 1),
        },
    }


# ---------- Portkey ----------

def provider_timeout_ms(catalog: dict, provider: str) -> int:
    return int(catalog["providers"][provider].get("request_timeout_ms") or policy(catalog)["portkey"]["default_timeout_ms"])


def target(catalog: dict, m: dict, s: dict, keys: dict[str, str]) -> dict:
    pk = policy(catalog)["portkey"]
    p = catalog["providers"][s["provider"]]
    key = keys.get(p["key_env"])
    if not key:
        refuse(f"{m['id']} via {s['provider']}: {p['key_env']} is not set in Portkey's .env")
    t = {"provider": p["portkey"], "api_key": key}
    if p.get("custom_host"):
        t["custom_host"] = p["custom_host"]
    if "strict_open_ai_compliance" in p:
        if not isinstance(p["strict_open_ai_compliance"], bool):
            refuse(f"{s['provider']}: strict_open_ai_compliance must be boolean")
        t["strict_open_ai_compliance"] = p["strict_open_ai_compliance"]
    t["override_params"] = {"model": s["provider_model_id"]}
    t["retry"] = {"attempts": pk["retry_attempts"], "on_status_codes": pk["retry_on_status_codes"]}
    t["request_timeout"] = provider_timeout_ms(catalog, s["provider"])
    if pk["mode"] == "loadbalance":
        t["weight"] = s.get("weight", 1)
    return t


def model_strategy(catalog: dict) -> dict:
    pk = policy(catalog)["portkey"]
    if pk["mode"] == "fallback":
        return {"mode": "fallback", "on_status_codes": pk["on_status_codes"]}
    return {"mode": pk["mode"]}


def model_config(catalog: dict, m: dict, keys: dict[str, str]) -> dict:
    return {
        "_": f"{GEN_JSON}; model {m['id']} in tier {m['tier']}",
        "strategy": model_strategy(catalog),
        "targets": [target(catalog, m, s, keys) for s in m["live"]],
    }


def tier_config(catalog: dict, models: list[dict], tier: str, keys: dict[str, str]) -> dict:
    return {
        "_": f"{GEN_JSON}; tier {tier}, models in order; LiteLLM is the normal path, this is for status checks",
        "strategy": {"mode": "fallback", "on_status_codes": policy(catalog)["portkey"]["on_status_codes"]},
        "targets": [
            {
                "strategy": model_strategy(catalog),
                "targets": [target(catalog, m, s, keys) for s in m["live"]],
            }
            for m in tier_models(models, tier)
        ],
    }


def probe_configs(catalog: dict, models: list[dict], keys: dict[str, str]) -> dict[str, dict]:
    """Provider -> a config with that provider alone, on the first routed model it serves."""
    out = {}
    for p in catalog["providers"]:
        hit = next(((m, s) for t in catalog["tiers"] for m in tier_models(models, t)
                    for s in m["live"] if s["provider"] == p), None)
        if hit:
            m, s = hit
            out[p] = {"_": f"{GEN_JSON}; probe for provider {p} on model {m['id']}", **target(catalog, m, s, keys)}
    return out


def pair_name(model_id: str, provider: str) -> str:
    return f"team-pair-{slug(model_id)}--{provider}"


def pair_configs(catalog: dict, keys: dict[str, str]) -> dict[str, dict]:
    """Config name -> that one model on that one provider. Every row has passed routed()'s free checks."""
    out = {}
    for m in catalog["models"]:
        for s in m["served_by"]:
            if keys.get(catalog["providers"][s["provider"]]["key_env"]):
                name = pair_name(m["id"], s["provider"])
                out[name] = {"_": f"{GEN_JSON}; verify {m['id']} on {s['provider']} alone",
                             **target(catalog, m, s, keys)}
    return out


def allowances(catalog: dict, models: list[dict], config_names: set[str]) -> dict:
    """Provider -> its allowance, prices by provider model id, and every config name that can reach it."""
    out = {}
    for p, spec in catalog["providers"].items():
        if "allowance" not in spec:
            continue
        a = spec["allowance"]
        mine = [m for m in catalog["models"] if any(s["provider"] == p for s in m["served_by"])]
        slugs = {slug(m["id"]) for m in mine}
        tiers = {m["tier"] for m in models if m["slug"] in slugs}
        configs = {f"team-model-{s}" for s in slugs} | {pair_name(m["id"], p) for m in mine} \
            | {f"team-probe-{p}"} | {f"team-tier-{t}" for t in tiers}
        keys = ("input_per_mtok", "output_per_mtok", "long_prompt_over", "long_input_per_mtok", "long_output_per_mtok")
        out[p] = {
            "portkey": spec["portkey"],
            "monthly_usd": a["monthly_usd"],
            "stop_at_usd": a["stop_at_usd"],
            "cycle_day": a["cycle_day"],
            "prices": {s["provider_model_id"]: {k: m["price"][k] for k in keys if k in m["price"]}
                       for m in mine for s in m["served_by"]},
            "configs": sorted(c for c in configs if c in config_names),
        }
    return out


def timeout_s(catalog: dict, m: dict) -> int:
    ms = sum(provider_timeout_ms(catalog, s["provider"]) for s in m["live"])
    return ms // 1000 + 10


# ---------- LiteLLM ----------

def deployment(catalog: dict, m: dict, group: str, dep_id: str) -> dict:
    g = catalog["gateway"]
    params = {
        "model": f"openai/{m['id']}",
        "api_base": f"http://{g['host']}:{g['port']}/v1",
        "api_key": "team",
        "extra_headers": {"x-portkey-config": f"team-model-{m['slug']}"},
        "order": m["order"],
        "timeout": timeout_s(catalog, m),
    }
    info = {"id": dep_id, "input_cost_per_token": 0, "output_cost_per_token": 0}
    cap = m.get("max_input") or m["live"][0].get("max_input") or m.get("context")
    if cap:
        info["max_input_tokens"] = cap
    if m.get("max_output"):
        info["max_output_tokens"] = m["max_output"]
    if m.get("tools") is not None:
        info["supports_function_calling"] = bool(m["tools"])
        info["supports_tool_choice"] = bool(m["tools"])
    if m.get("vision") is not None:
        info["supports_vision"] = bool(m["vision"])
    if m.get("reasoning") is not None:
        info["supports_reasoning"] = bool(m["reasoning"])
    return {"model_name": group, "litellm_params": params, "model_info": info}


def litellm_config(catalog: dict, models: list[dict]) -> dict:
    tiers = catalog["tiers"]
    model_list = []
    for t in tiers:
        for m in tier_models(models, t):
            model_list.append(deployment(catalog, m, m["id"], m["slug"]))
            model_list.append(deployment(catalog, m, f"tier-{t}", f"tier-{t}/{m['slug']}"))
    fb = catalog["tier_fallbacks"]
    ll = policy(catalog)["litellm"]
    router = {"routing_strategy": ll["routing_strategy"]} if ll["routing_strategy"] else {}
    router.update({
        "enable_pre_call_checks": ll["enable_pre_call_checks"],
        "num_retries": ll["num_retries"],
        "max_fallbacks": ll["max_fallbacks"],
        "allowed_fails": ll["allowed_fails"],
        "cooldown_time": ll["cooldown_time"],
        "fallbacks": [{f"tier-{t}": [f"tier-{f}" for f in fb[t]]} for t in tiers],
        "context_window_fallbacks": [
            {f"tier-{t}": [f"tier-{f}" for f in to]} for t, to in ll["context_window_fallbacks"].items()
        ],
    })
    return {
        "model_list": model_list,
        "router_settings": router,
        "litellm_settings": {
            "drop_params": ll["drop_params"],
            "telemetry": False,
            "callbacks": ["spend_guard.guard", "forward_headers.forward", "session_pin.pin", "usage_log.logger"],
        },
        "general_settings": {
            "master_key": "os.environ/LITELLM_MASTER_KEY",
            # Otherwise the proxy sweeps every deployment's /v1/models on start and on a timer,
            # which Portkey forwards to every provider (109 such calls on 2026-10-27 before this).
            "disable_model_info_refresh": True,
        },
    }


# ---------- all four ----------

def render(catalog: dict, keys: dict[str, str]) -> dict[str, str]:
    """Relative path under the state dir -> exact file text."""
    models = routed(catalog)
    out: dict[str, str] = {}
    for m in models:
        out[f"portkey/configs/team-model-{m['slug']}.json"] = json_dump(model_config(catalog, m, keys))
    for t in catalog["tiers"]:
        out[f"portkey/configs/team-tier-{t}.json"] = json_dump(tier_config(catalog, models, t, keys))
    for p, cfg in probe_configs(catalog, models, keys).items():
        out[f"portkey/configs/team-probe-{p}.json"] = json_dump(cfg)
    for name, cfg in pair_configs(catalog, keys).items():
        path = f"portkey/configs/{name}.json"
        if path in out:
            refuse(f"{name}: two models share a slug")
        out[path] = json_dump(cfg)
    for path, text in out.items():
        if len(text.encode()) > MAX_CONFIG_BYTES:
            refuse(f"{path} is {len(text.encode())} bytes, over {MAX_CONFIG_BYTES}")
    head = "# GENERATED by integrations/portkey/build.py from catalog.json. Edit the catalog, then rebuild.\n"
    out["litellm/config.yaml"] = head + yaml_dump(litellm_config(catalog, models))
    names = {p.rsplit("/", 1)[1][:-5] for p in out if p.startswith("portkey/configs/")}
    out["litellm/allowances.json"] = json_dump(allowances(catalog, models, names))
    return out


def generated_on_disk(state: Path) -> set[str]:
    cfg = state / "portkey" / "configs"
    return {f"portkey/configs/{p.name}" for p in cfg.glob("team-*.json")} if cfg.exists() else set()


def drift(state: Path, files: dict[str, str]) -> list[str]:
    problems = []
    for rel, text in files.items():
        p = state / rel
        if not p.exists():
            problems.append(f"missing {rel}")
        elif p.read_text() != text:
            problems.append(f"differs {rel}")
    for rel in sorted(generated_on_disk(state) - set(files)):
        problems.append(f"stale {rel}")
    return problems


def write(state: Path, files: dict[str, str]) -> None:
    for rel in generated_on_disk(state) - set(files):
        (state / rel).unlink()
    for rel, text in files.items():
        p = state / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        tmp = p.with_name(p.name + ".tmp")
        with open(os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600), "w") as f:
            f.write(text)
        os.chmod(tmp, 0o600)
        os.replace(tmp, p)


def main(argv: list[str]) -> int:
    state = state_dir()
    catalog = json.loads(CATALOG.read_text())
    keys = read_env(state / "portkey" / ".env")
    files = render(catalog, keys)
    if "--check" in argv:
        problems = drift(state, files)
        if problems:
            refuse("outputs are not what catalog.json generates: " + "; ".join(problems) + "; run build.py")
        print(f"build.py --check: {len(files)} files match catalog.json")
        return 0
    write(state, files)
    print(f"build.py: wrote {len(files)} files under {state}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
