//! `gateway-rs build [--check]`: one catalog in, the same files out as integrations/portkey/build.py,
//! byte for byte. Read both side by side; the structure is the same on purpose.

use serde_json::{Map, Value, json};
use std::collections::HashMap;
use std::fs;
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};

pub const FREE: [&str; 2] = ["yes", "allowance"];
pub const MAX_CONFIG_BYTES: usize = 12 * 1024;
pub const ON_STATUS: [u64; 11] = [401, 402, 403, 404, 408, 429, 500, 502, 503, 504, 529];
pub const RETRY_STATUS: [u64; 4] = [500, 502, 503, 504];
pub const DEFAULT_TIMEOUT_MS: u64 = 60000;
pub const GEN_JSON: &str =
    "generated by integrations/portkey/build.py from catalog.json; edit the catalog, then rebuild";

#[derive(Debug)]
pub struct Refusal(pub String);

impl std::fmt::Display for Refusal {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "refusing: {}", self.0)
    }
}

fn refuse<T>(msg: impl Into<String>) -> Result<T, Refusal> {
    Err(Refusal(msg.into()))
}

pub fn state_dir() -> PathBuf {
    match std::env::var("TEAM_STATE") {
        Ok(s) if !s.is_empty() => PathBuf::from(s),
        _ => PathBuf::from(std::env::var("HOME").expect("HOME")).join("state").join("team"),
    }
}

/// KEY=value lines; no quoting, no expansion, # comments.
pub fn read_env(path: &Path) -> Result<HashMap<String, String>, Refusal> {
    let text = match fs::read_to_string(path) {
        Ok(t) => t,
        Err(_) => {
            return refuse(format!(
                "{} is missing; it must hold every provider key named in the catalog",
                path.display()
            ));
        }
    };
    let mut out = HashMap::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') || !line.contains('=') {
            continue;
        }
        let (k, v) = line.split_once('=').unwrap();
        out.insert(k.trim().to_string(), v.trim().to_string());
    }
    Ok(out)
}

pub fn slug(model_id: &str) -> String {
    model_id
        .chars()
        .map(|c| if c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' { c } else { '-' })
        .collect()
}

fn is_name(s: &str) -> bool {
    !s.is_empty() && s.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-')
}

// ---------- YAML emitter (deterministic, subset), the twin of build.py's ----------

const RESERVED: [&str; 9] = ["true", "false", "null", "yes", "no", "on", "off", "y", "n"];

fn plain(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | '/' | '-'))
}

fn yscalar(v: &Value) -> String {
    match v {
        Value::Null => "null".into(),
        Value::Bool(true) => "true".into(),
        Value::Bool(false) => "false".into(),
        Value::Number(n) => n.to_string(),
        Value::String(s) => {
            if (plain(s) && !RESERVED.contains(&s.to_lowercase().as_str())) || s == "~" && false {
                s.clone()
            } else if s == "~" {
                serde_json::to_string(s).unwrap()
            } else {
                serde_json::to_string(s).unwrap()
            }
        }
        other => serde_json::to_string(other).unwrap(),
    }
}

fn non_empty_container(v: &Value) -> bool {
    match v {
        Value::Object(m) => !m.is_empty(),
        Value::Array(a) => !a.is_empty(),
        _ => false,
    }
}

fn yaml_lines(v: &Value, indent: usize) -> Vec<String> {
    let pad = " ".repeat(indent);
    match v {
        Value::Object(m) => {
            if m.is_empty() {
                return vec![format!("{pad}{{}}")];
            }
            let mut out = Vec::new();
            for (k, val) in m {
                let key = yscalar(&Value::String(k.clone()));
                match val {
                    Value::Object(inner) if !inner.is_empty() => {
                        out.push(format!("{pad}{key}:"));
                        out.extend(yaml_lines(val, indent + 2));
                    }
                    Value::Array(inner) if !inner.is_empty() => {
                        out.push(format!("{pad}{key}:"));
                        out.extend(yaml_lines(val, indent));
                    }
                    _ => out.push(format!("{pad}{key}: {}", yaml_lines(val, 0)[0])),
                }
            }
            out
        }
        Value::Array(a) => {
            if a.is_empty() {
                return vec![format!("{pad}[]")];
            }
            let mut out = Vec::new();
            for item in a {
                if non_empty_container(item) {
                    let sub = yaml_lines(item, indent + 2);
                    out.push(format!("{pad}- {}", &sub[0][indent + 2..]));
                    out.extend(sub[1..].iter().cloned());
                } else {
                    out.push(format!("{pad}- {}", yaml_lines(item, 0)[0]));
                }
            }
            out
        }
        _ => vec![format!("{pad}{}", yscalar(v))],
    }
}

pub fn yaml_dump(v: &Value) -> String {
    let mut s = yaml_lines(v, 0).join("\n");
    s.push('\n');
    s
}

pub fn json_dump(v: &Value) -> String {
    let mut s = serde_json::to_string_pretty(v).unwrap();
    s.push('\n');
    s
}

// ---------- the catalog, checked ----------

pub struct Routed {
    pub id: String,
    pub tier: String,
    pub order: u64,
    pub slug: String,
    pub raw: Map<String, Value>,
    pub live: Vec<Map<String, Value>>,
}

fn s<'a>(m: &'a Map<String, Value>, k: &str) -> Option<&'a str> {
    m.get(k).and_then(Value::as_str)
}

fn u(m: &Map<String, Value>, k: &str) -> Option<u64> {
    m.get(k).and_then(Value::as_u64).filter(|n| *n != 0)
}

pub fn routed(catalog: &Map<String, Value>) -> Result<Vec<Routed>, Refusal> {
    let blocked = catalog["blocked_providers"].as_object().unwrap();
    let providers = catalog["providers"].as_object().unwrap();
    let tiers: Vec<&str> = catalog["tiers"].as_array().unwrap().iter().filter_map(Value::as_str).collect();
    let mut seen_ids = std::collections::HashSet::new();
    let mut seen_slugs = std::collections::HashSet::new();
    let mut out = Vec::new();
    for m in catalog["models"].as_array().unwrap() {
        let m = m.as_object().unwrap();
        let mid = s(m, "id").unwrap_or("");
        if !seen_ids.insert(mid.to_string()) {
            return refuse(format!("{mid}: duplicate model id"));
        }
        let served: Vec<&Map<String, Value>> = m
            .get("served_by")
            .and_then(Value::as_array)
            .map(|a| a.iter().filter_map(Value::as_object).collect())
            .unwrap_or_default();
        if served.is_empty() {
            return refuse(format!("{mid}: no served_by"));
        }
        for sb in &served {
            let p = s(sb, "provider").unwrap_or("");
            if let Some(why) = blocked.get(p) {
                return refuse(format!("{mid}: provider {p} is blocked ({})", why.as_str().unwrap_or("")));
            }
            if !providers.contains_key(p) {
                return refuse(format!("{mid}: unknown provider {p}"));
            }
            match s(sb, "free") {
                Some(f) if FREE.contains(&f) => {}
                other => {
                    let shown = match other {
                        Some(f) => format!("'{f}'"),
                        None => "None".into(),
                    };
                    return refuse(format!("{mid} via {p}: free is {shown}"));
                }
            }
            let pmid = s(sb, "provider_model_id").unwrap_or("");
            if p == "openrouter" && !pmid.ends_with(":free") {
                return refuse(format!("{mid} via openrouter: {pmid} is not a ':free' variant"));
            }
        }
        let tier = match m.get("tier") {
            None | Some(Value::Null) => continue,
            Some(Value::String(t)) => t.clone(),
            Some(other) => return refuse(format!("{mid}: unknown tier {other}")),
        };
        if !tiers.contains(&tier.as_str()) {
            return refuse(format!("{mid}: unknown tier '{tier}'"));
        }
        let order = match m.get("order").and_then(Value::as_i64) {
            Some(o) if o >= 1 => o as u64,
            _ => return refuse(format!("{mid}: order must be an integer >= 1")),
        };
        let sl = slug(mid);
        if !is_name(&sl) {
            return refuse(format!("{mid}: slug '{sl}' is not a config name"));
        }
        if !seen_slugs.insert(sl.clone()) {
            return refuse(format!("{mid}: slug {sl} collides with another model"));
        }
        let live: Vec<Map<String, Value>> = served
            .iter()
            .filter(|sb| !sb.get("unavailable").map(|v| !v.is_null()).unwrap_or(false))
            .map(|sb| (*sb).clone())
            .collect();
        if live.is_empty() {
            return refuse(format!("{mid}: routed in tier {tier} but every provider is marked unavailable"));
        }
        out.push(Routed { id: mid.to_string(), tier, order, slug: sl, raw: m.clone(), live });
    }
    for t in &tiers {
        if !out.iter().any(|m| m.tier == *t) {
            return refuse(format!("tier {t} has no models"));
        }
    }
    for (p, spec) in providers {
        if blocked.contains_key(p) {
            return refuse(format!("provider {p} is both configured and blocked"));
        }
        let spec = spec.as_object().unwrap();
        if s(spec, "portkey").unwrap_or("").is_empty() || s(spec, "key_env").unwrap_or("").is_empty() {
            return refuse(format!("provider {p}: needs 'portkey' slug and 'key_env'"));
        }
    }
    Ok(out)
}

fn tier_models<'a>(models: &'a [Routed], tier: &str) -> Vec<&'a Routed> {
    let mut v: Vec<&Routed> = models.iter().filter(|m| m.tier == tier).collect();
    v.sort_by_key(|m| m.order); // stable, like Python's sorted
    v
}

// ---------- Portkey ----------

fn provider<'a>(catalog: &'a Map<String, Value>, name: &str) -> &'a Map<String, Value> {
    catalog["providers"][name].as_object().unwrap()
}

fn target(
    catalog: &Map<String, Value>,
    m: &Routed,
    sb: &Map<String, Value>,
    keys: &HashMap<String, String>,
) -> Result<Value, Refusal> {
    let pname = s(sb, "provider").unwrap();
    let p = provider(catalog, pname);
    let key_env = s(p, "key_env").unwrap();
    let key = match keys.get(key_env) {
        Some(k) if !k.is_empty() => k.clone(),
        _ => return refuse(format!("{} via {pname}: {key_env} is not set in Portkey's .env", m.id)),
    };
    let mut t = Map::new();
    t.insert("provider".into(), json!(s(p, "portkey").unwrap()));
    t.insert("api_key".into(), json!(key));
    if let Some(h) = s(p, "custom_host").filter(|h| !h.is_empty()) {
        t.insert("custom_host".into(), json!(h));
    }
    t.insert("override_params".into(), json!({"model": s(sb, "provider_model_id").unwrap()}));
    t.insert("retry".into(), json!({"attempts": 1, "on_status_codes": RETRY_STATUS}));
    t.insert("request_timeout".into(), json!(u(p, "request_timeout_ms").unwrap_or(DEFAULT_TIMEOUT_MS)));
    Ok(Value::Object(t))
}

fn strategy() -> Value {
    json!({"mode": "fallback", "on_status_codes": ON_STATUS})
}

fn model_config(catalog: &Map<String, Value>, m: &Routed, keys: &HashMap<String, String>) -> Result<Value, Refusal> {
    let targets = m.live.iter().map(|sb| target(catalog, m, sb, keys)).collect::<Result<Vec<_>, _>>()?;
    Ok(json!({
        "_": format!("{GEN_JSON}; model {} in tier {}", m.id, m.tier),
        "strategy": strategy(),
        "targets": targets,
    }))
}

fn tier_config(
    catalog: &Map<String, Value>,
    models: &[Routed],
    tier: &str,
    keys: &HashMap<String, String>,
) -> Result<Value, Refusal> {
    let mut targets = Vec::new();
    for m in tier_models(models, tier) {
        let inner = m.live.iter().map(|sb| target(catalog, m, sb, keys)).collect::<Result<Vec<_>, _>>()?;
        targets.push(json!({"strategy": strategy(), "targets": inner}));
    }
    Ok(json!({
        "_": format!("{GEN_JSON}; tier {tier}, models in order; LiteLLM is the normal path, this is for status checks"),
        "strategy": strategy(),
        "targets": targets,
    }))
}

fn timeout_s(catalog: &Map<String, Value>, m: &Routed) -> u64 {
    let ms: u64 = m
        .live
        .iter()
        .map(|sb| u(provider(catalog, s(sb, "provider").unwrap()), "request_timeout_ms").unwrap_or(DEFAULT_TIMEOUT_MS))
        .sum();
    ms / 1000 + 10
}

// ---------- LiteLLM ----------

fn deployment(catalog: &Map<String, Value>, m: &Routed, group: &str, dep_id: &str) -> Value {
    let g = catalog["gateway"].as_object().unwrap();
    let params = json!({
        "model": format!("openai/{}", m.id),
        "api_base": format!("http://{}:{}/v1", s(g, "host").unwrap(), g["port"]),
        "api_key": "team",
        "extra_headers": {"x-portkey-config": format!("team-model-{}", m.slug)},
        "order": m.order,
        "timeout": timeout_s(catalog, m),
    });
    let mut info = Map::new();
    info.insert("id".into(), json!(dep_id));
    info.insert("input_cost_per_token".into(), json!(0));
    info.insert("output_cost_per_token".into(), json!(0));
    let cap = u(&m.raw, "max_input").or_else(|| u(&m.live[0], "max_input")).or_else(|| u(&m.raw, "context"));
    if let Some(c) = cap {
        info.insert("max_input_tokens".into(), json!(c));
    }
    if let Some(o) = u(&m.raw, "max_output") {
        info.insert("max_output_tokens".into(), json!(o));
    }
    if let Some(t) = m.raw.get("tools").filter(|v| !v.is_null()) {
        let b = truthy(t);
        info.insert("supports_function_calling".into(), json!(b));
        info.insert("supports_tool_choice".into(), json!(b));
    }
    if let Some(v) = m.raw.get("vision").filter(|v| !v.is_null()) {
        info.insert("supports_vision".into(), json!(truthy(v)));
    }
    if let Some(r) = m.raw.get("reasoning").filter(|v| !v.is_null()) {
        info.insert("supports_reasoning".into(), json!(truthy(r)));
    }
    json!({"model_name": group, "litellm_params": params, "model_info": info})
}

fn truthy(v: &Value) -> bool {
    match v {
        Value::Bool(b) => *b,
        Value::Null => false,
        Value::Number(n) => n.as_f64() != Some(0.0),
        Value::String(s) => !s.is_empty(),
        Value::Array(a) => !a.is_empty(),
        Value::Object(o) => !o.is_empty(),
    }
}

fn litellm_config(catalog: &Map<String, Value>, models: &[Routed]) -> Value {
    let tiers: Vec<&str> = catalog["tiers"].as_array().unwrap().iter().filter_map(Value::as_str).collect();
    let mut model_list = Vec::new();
    for t in &tiers {
        for m in tier_models(models, t) {
            model_list.push(deployment(catalog, m, &m.id, &m.slug));
            model_list.push(deployment(catalog, m, &format!("tier-{t}"), &format!("tier-{t}/{}", m.slug)));
        }
    }
    let fb = catalog["tier_fallbacks"].as_object().unwrap();
    let fallbacks: Vec<Value> = tiers
        .iter()
        .map(|t| {
            let next: Vec<String> = fb[*t].as_array().unwrap().iter().map(|f| format!("tier-{}", f.as_str().unwrap())).collect();
            json!({format!("tier-{t}"): next})
        })
        .collect();
    json!({
        "model_list": model_list,
        "router_settings": {
            "enable_pre_call_checks": true,
            "num_retries": 1,
            "max_fallbacks": 2,
            "allowed_fails": 1,
            "cooldown_time": 300,
            "fallbacks": fallbacks,
            "context_window_fallbacks": [],
        },
        "litellm_settings": {
            "drop_params": true,
            "telemetry": false,
            "callbacks": ["forward_headers.forward", "session_pin.pin", "usage_log.logger"],
        },
        "general_settings": {"master_key": "os.environ/LITELLM_MASTER_KEY", "disable_model_info_refresh": true},
    })
}

// ---------- all outputs ----------

/// Relative path under the state dir -> exact file text, in build.py's order.
pub fn render(catalog: &Map<String, Value>, keys: &HashMap<String, String>) -> Result<Vec<(String, String)>, Refusal> {
    let models = routed(catalog)?;
    let mut out: Vec<(String, String)> = Vec::new();
    for m in &models {
        out.push((format!("portkey/configs/team-model-{}.json", m.slug), json_dump(&model_config(catalog, m, keys)?)));
    }
    for t in catalog["tiers"].as_array().unwrap().iter().filter_map(Value::as_str) {
        out.push((format!("portkey/configs/team-tier-{t}.json"), json_dump(&tier_config(catalog, &models, t, keys)?)));
    }
    for (path, text) in &out {
        if text.len() > MAX_CONFIG_BYTES {
            return refuse(format!("{path} is {} bytes, over {MAX_CONFIG_BYTES}", text.len()));
        }
    }
    let head = "# GENERATED by integrations/portkey/build.py from catalog.json. Edit the catalog, then rebuild.\n";
    out.push(("litellm/config.yaml".into(), format!("{head}{}", yaml_dump(&litellm_config(catalog, &models)))));
    Ok(out)
}

pub fn generated_on_disk(state: &Path) -> Vec<String> {
    let cfg = state.join("portkey").join("configs");
    let mut v = Vec::new();
    if let Ok(rd) = fs::read_dir(&cfg) {
        for e in rd.flatten() {
            let name = e.file_name().to_string_lossy().to_string();
            if name.starts_with("team-") && name.ends_with(".json") {
                v.push(format!("portkey/configs/{name}"));
            }
        }
    }
    v.sort();
    v
}

pub fn drift(state: &Path, files: &[(String, String)]) -> Vec<String> {
    let mut problems = Vec::new();
    for (rel, text) in files {
        let p = state.join(rel);
        match fs::read_to_string(&p) {
            Err(_) => problems.push(format!("missing {rel}")),
            Ok(t) if &t != text => problems.push(format!("differs {rel}")),
            Ok(_) => {}
        }
    }
    let known: std::collections::HashSet<&str> = files.iter().map(|(r, _)| r.as_str()).collect();
    for rel in generated_on_disk(state) {
        if !known.contains(rel.as_str()) {
            problems.push(format!("stale {rel}"));
        }
    }
    problems
}

pub fn write(state: &Path, files: &[(String, String)]) -> std::io::Result<()> {
    let known: std::collections::HashSet<&str> = files.iter().map(|(r, _)| r.as_str()).collect();
    for rel in generated_on_disk(state) {
        if !known.contains(rel.as_str()) {
            fs::remove_file(state.join(rel))?;
        }
    }
    for (rel, text) in files {
        let p = state.join(rel);
        fs::create_dir_all(p.parent().unwrap())?;
        let tmp = p.with_file_name(format!("{}.tmp", p.file_name().unwrap().to_string_lossy()));
        {
            use std::io::Write;
            let mut f = fs::OpenOptions::new().write(true).create(true).truncate(true).mode(0o600).open(&tmp)?;
            f.write_all(text.as_bytes())?;
        }
        fs::set_permissions(&tmp, fs::Permissions::from(std::os::unix::fs::PermissionsExt::from_mode(0o600)))?;
        fs::rename(&tmp, &p)?;
    }
    Ok(())
}

pub fn run(catalog_path: &Path, check: bool) -> Result<String, String> {
    let state = state_dir();
    let text = fs::read_to_string(catalog_path).map_err(|e| format!("cannot read {}: {e}", catalog_path.display()))?;
    let catalog: Value = serde_json::from_str(&text).map_err(|e| format!("catalog is not JSON: {e}"))?;
    let catalog = catalog.as_object().ok_or("catalog is not an object")?;
    let keys = read_env(&state.join("portkey").join(".env")).map_err(|e| e.to_string())?;
    let files = render(catalog, &keys).map_err(|e| e.to_string())?;
    if check {
        let problems = drift(&state, &files);
        if !problems.is_empty() {
            return Err(format!(
                "refusing: outputs are not what catalog.json generates: {}; run build",
                problems.join("; ")
            ));
        }
        return Ok(format!("build --check: {} files match catalog.json", files.len()));
    }
    write(&state, &files).map_err(|e| format!("write failed: {e}"))?;
    Ok(format!("build: wrote {} files under {}", files.len(), state.display()))
}
