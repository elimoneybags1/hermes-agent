"""Orchestration settings: how ``team run`` behaves.

``team/orchestration.toml`` holds the rules of the loop, the same for every
target; each change is a git commit, like an agent change. Per-target
settings (``check``, ``enabled``) live in the target record under
``$TEAM_STATE`` (see ``team.targets``). Retries before escalation are per
role (``escalation.after_failures`` in ``role.toml``).
"""

from __future__ import annotations

import tomllib
from pathlib import Path
from typing import Any

from team import grade, targets

FILE = "team/orchestration.toml"

# key: (type, default, help)
FIELDS: dict[str, tuple[type, Any, str]] = {
    "loop.interval_s": (int, 60, "Seconds between ticks of `team run`."),
    "loop.max_new_per_tick": (int, 3, "Most new kanban workers one tick may spawn."),
    "grading.default_check": (
        str,
        "pytest -q",
        'The check that decides "done" when a target has none of its own.',
    ),
    "grading.check_timeout_s": (int, 900, "A check running longer than this fails."),
    "escalation.claude": (
        bool,
        True,
        "After a role's free attempts fail, try once on Claude Code (subscription).",
    ),
    "escalation.claude_max_turns": (int, 60, "Turn limit for a Claude Code attempt."),
    "escalation.claude_timeout_s": (int, 1800, "Time limit for a Claude Code attempt."),
    "ask.block_after_claude_fails": (
        bool,
        True,
        "When the Claude attempt fails too, block the task and ask Eli.",
    ),
}


class SettingsError(ValueError):
    """A setting that does not exist or a value it cannot take."""


def _read(root: Path) -> dict:
    path = Path(root) / FILE
    if not path.exists():
        return {}
    with path.open("rb") as f:
        return tomllib.load(f)


def _coerce(key: str, kind: type, value: Any) -> Any:
    if kind is bool:
        if not isinstance(value, bool):
            raise SettingsError(f"{key} must be true or false")
    elif kind is int:
        if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
            raise SettingsError(f"{key} must be a whole number above 0")
    elif kind is str:
        if not isinstance(value, str) or not value.strip():
            raise SettingsError(f"{key} must be a non-empty string")
        value = value.strip()
    return value


def load(root: Path) -> dict[str, Any]:
    """Every setting as a flat ``{"section.key": value}``, defaults filled in."""
    data = _read(root)
    out = {}
    for key, (kind, default, _) in FIELDS.items():
        section, name = key.split(".", 1)
        value = data.get(section, {}).get(name, default)
        out[key] = _coerce(key, kind, value) if value != default else default
    return out


def fields() -> list[dict[str, Any]]:
    """The settings a page can edit, with their types and help text."""
    return [
        {"key": k, "type": t.__name__, "default": d, "help": h}
        for k, (t, d, h) in FIELDS.items()
    ]


def _toml_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _dump(data: dict) -> str:
    """Serialize the two-level dict of scalars that orchestration.toml holds."""
    lines = ["# Generated by `team settings set`; every change is a commit.", ""]
    for section in sorted(data):
        lines.append(f"[{section}]")
        for name, value in sorted(data[section].items()):
            lines.append(f"{name} = {_toml_value(value)}")
        lines.append("")
    return "\n".join(lines)


def set_value(root: Path, key: str, value: Any, source: str = "cli") -> str:
    """Change one setting in orchestration.toml and commit it; returns the sha."""
    if key not in FIELDS:
        raise SettingsError(f"unknown setting: {key}")
    value = _coerce(key, FIELDS[key][0], value)
    data = _read(root)
    section, name = key.split(".", 1)
    data.setdefault(section, {})[name] = value
    path = Path(root) / FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_dump(data))
    return grade.commit_paths(root, f"settings: {key} = {value!r} ({source})", path)


def check_for(root: Path, name: str) -> str:
    """The check command that decides "done" for this target."""
    return targets.require(name).get("check") or load(root)["grading.default_check"]
